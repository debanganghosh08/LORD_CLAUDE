# --- js/ts extractor -------------------------------------------------------------

def test_js_extractor_declarations_imports_and_resolution():
    ex = extract_js_ts(FIXTURE, "web/app.js", (FIXTURE / "web/app.js").read_text(encoding="utf-8"), "javascript")
    assert ex.confidence == INFERRED
    by_qual = {s.qualname: s for s in ex.symbols}
    assert by_qual["render"].kind == "function"
    assert by_qual["Widget"].kind == "class" and by_qual["Widget"].exported
    assert by_qual["Widget.draw"].kind == "method" and by_qual["Widget.draw"].parent == "Widget"
    assert by_qual["MAX_ITEMS"].kind == "constant" and by_qual["onClick"].kind == "function"
    assert any(s.kind == "route" and "/items" in s.name for s in ex.symbols)
    assert [(b.qualname, b.base) for b in ex.bases] == [("Widget", "Base")]
    helper = next(i for i in ex.imports if i.module == "./lib/helper")
    assert helper.resolved == "web/lib/helper.js" and helper.names == ["helper", "helperConst"] and helper.aliases == ["h", "helperConst"]
    react = next(i for i in ex.imports if i.module == "react")
    assert react.resolved is None and react.names == ["default"] and react.aliases == ["React"]
    assert ("h", "render") in {(c.name, c.scope) for c in ex.calls}
    assert {"Widget", "render"} <= set(ex.exports)


