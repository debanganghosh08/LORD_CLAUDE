# --- index ---------------------------------------------------------------------------

def test_index_builds_persists_and_reuses(repo: Path):
    config = load_config(repo)
    index, report = build_index(config)
    assert index_path(repo).is_file() and index_path(repo).parent.name == ".lord"
    data = report.findings[0].data
    assert data["extracted"] >= 6 and data["reused"] == 0
    assert any(f.kind == "parse-errors" and f.confidence == UNKNOWN for f in report.findings)
    assert any(f.kind == "unsupported-languages" and "rust" in f.summary for f in report.findings)

    loaded = load_index(repo)
    assert loaded is not None and set(loaded.entries) == set(index.entries)

    (repo / "pkg" / "validators.py").write_text((repo / "pkg" / "validators.py").read_text(encoding="utf-8") + "\nNEW_CONST = 1\n", encoding="utf-8")
    index2, report2 = build_index(config, previous=loaded)
    data2 = report2.findings[0].data
    assert data2["extracted"] == 1 and data2["reused"] == len(index.entries) - 1
    assert any(s.name == "NEW_CONST" for s in index2.symbols_in("pkg/validators.py"))


