# --- cli -------------------------------------------------------------------------------

def test_cli_forensics_commands_json(repo: Path):
    def run(*args: str) -> dict:
        completed = subprocess.run([sys.executable, "-m", "lord", "--root", str(repo), *args, "--json"], cwd=ROOT, capture_output=True, text=True)
        assert completed.returncode == 0, completed.stderr
        return json.loads(completed.stdout)

    assert run("inventory")["meta"]["files"] >= 14
    assert run("index")["findings"][0]["kind"] == "index"
    assert run("def", "normalize_email")["findings"][0]["summary"].startswith("pkg/utils/strings.py:4")
    assert run("refs", "normalize_email")["meta"]["confirmed_files"] == 1
    assert run("dependents", "pkg/utils/strings.py")["meta"]["dependents"] == ["pkg/users.py"]
    assert run("symbols", "web\\app.js")["meta"]["language"] == "javascript"
    assert run("related", "slug generation")["findings"][0]["data"]["symbol"]["name"] == "slugify"
