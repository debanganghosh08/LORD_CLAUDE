# --- queries ---------------------------------------------------------------------------

def test_definition_query(index):
    report = query.definition(index, "validate_email")
    summaries = [f.summary for f in report.findings if f.kind == "definition"]
    assert summaries == ["pkg/validators.py:8 function validate_email (value)"]
    assert report.findings[0].confidence == CONFIRMED
    assert query.definition(index, "UserService.create").findings[0].summary.startswith("pkg/users.py:10 method UserService.create")
    missing = query.definition(index, "does_not_exist")
    assert missing.findings[0].severity == "warn"


def test_references_separate_confirmed_from_text_matches(index, repo: Path):
    report = query.references(index, repo, "validate_email")
    confirmed = {f.data["path"]: f for f in report.findings if f.kind == "reference" and f.confidence == CONFIRMED}
    inferred = {f.data["path"]: f for f in report.findings if f.kind == "reference" and f.confidence == INFERRED}
    assert set(confirmed) == {"pkg/users.py", "tests/test_validators.py"}
    assert "UserService.create" in confirmed["pkg/users.py"].data["scopes"]
    assert "native/main.rs" in inferred, "unsupported language must surface as a text match, not vanish"
    assert "pkg/users.py" in inferred and 13 in inferred["pkg/users.py"].data["lines"]  # the comment mention
    assert "pkg/users.py::UserService.create" in report.meta["callers"]
    assert any(f.kind == "analysis-unavailable" and f.confidence == UNKNOWN and "rust" in " ".join(f.evidence) for f in report.findings)


def test_related_finds_behavioural_matches(index):
    report = query.related(index, "email normalization")
    names = [f.data["symbol"]["qualname"] for f in report.findings if f.kind == "candidate"]
    assert names[0] == "normalize_email"
    assert "validate_email" in names
    report2 = query.related(index, "check that an e-mail address is valid")
    assert [f.data["symbol"]["qualname"] for f in report2.findings if f.kind == "candidate"][0] == "validate_email"


def test_deps_and_dependents(index):
    d = query.deps(index, "pkg/users.py")
    assert d.meta["internal"] == ["pkg/validators.py", "pkg/utils/strings.py"] and "os" in d.meta["external"]
    u = query.dependents(index, "pkg/validators.py")
    assert u.meta["dependents"] == ["pkg/users.py", "tests/test_validators.py"]
    assert all(f.confidence == CONFIRMED for f in u.findings if f.kind == "used-by")
    js = query.dependents(index, "web/lib/helper.js")
    assert js.meta["dependents"] == ["web/app.js"] and js.findings[0].confidence == INFERRED
    assert query.deps(index, "native/main.rs").findings[0].confidence == UNKNOWN


