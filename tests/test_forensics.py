# --- inventory ----------------------------------------------------------------

def test_inventory_classifies_and_excludes(repo: Path):
    inv = build_inventory(load_config(repo))
    kinds = {f.path: f.kind for f in inv.files}
    assert kinds["pkg/validators.py"] == "source"
    assert kinds["tests/test_validators.py"] == "test"
    assert kinds["pyproject.toml"] == "manifest"
    assert kinds["config/settings.yaml"] == "config"
    assert kinds["README.md"] == "docs"
    assert kinds["scripts/run.sh"] == "script"
    assert kinds["data/sample.csv"] == "data"
    assert kinds["generated/schema_pb2.py"] == "generated"
    assert kinds["native/main.rs"] == "source"
    assert not any(p.startswith(("node_modules/", "build/")) for p in kinds)
    assert {"node_modules", "build"} <= set(inv.excluded_dirs)
    assert inv.project_roots == ["."]
    summary = summarize(inv)
    assert summary["by_language"]["python"] >= 4 and summary["by_kind"]["generated"] == 1


def test_generated_marker_detected_by_header(tmp_path: Path):
    (tmp_path / "x.py").write_text("# Code generated by tool. DO NOT EDIT.\nX = 1\n", encoding="utf-8")
    inv = build_inventory(LordConfig(root=tmp_path))
    assert inv.files[0].kind == "generated" and "marker" in inv.files[0].reason


def test_generated_marker_outside_header_is_ignored(tmp_path: Path):
    body = "\n".join(["# ordinary module"] * 6) + "\nMARKERS = ('DO NOT EDIT', '@generated')\n"
    (tmp_path / "y.py").write_text(body, encoding="utf-8")
    inv = build_inventory(LordConfig(root=tmp_path))
    assert inv.files[0].kind == "source", "a marker mentioned in code must not classify the file as generated"


def test_exclusions_are_configurable(repo: Path):
    (repo / "lord.toml").write_text('[lord]\nextra_exclude_dirs = ["web"]\n', encoding="utf-8")
    inv = build_inventory(load_config(repo))
    assert not any(f.path.startswith("web/") for f in inv.files) and "web" in inv.excluded_dirs


# --- python extractor ----------------------------------------------------------

def test_python_extractor_symbols_imports_calls_bases():
    ex = extract_python(FIXTURE, "pkg/users.py", (FIXTURE / "pkg/users.py").read_text(encoding="utf-8"))
    assert ex.confidence == CONFIRMED and not ex.error
    by_qual = {s.qualname: s for s in ex.symbols}
    assert by_qual["UserService"].kind == "class" and by_qual["UserService"].doc == "Creates users."
    assert by_qual["UserService.create"].kind == "method" and by_qual["UserService.create"].parent == "UserService"
    assert by_qual["handler"].kind == "function"
    assert [(b.qualname, b.base) for b in ex.bases] == [("AdminService", "UserService")]
    imports = {i.module: i for i in ex.imports}
    assert imports["pkg.validators"].resolved == "pkg/validators.py" and imports["pkg.validators"].confidence == CONFIRMED
    assert imports[".utils.strings"].resolved == "pkg/utils/strings.py" and imports[".utils.strings"].is_relative
    assert imports["os"].resolved is None and imports["os"].confidence == INFERRED
    calls = {(c.name, c.scope) for c in ex.calls}
    assert ("validate_email", "UserService.create") in calls and ("normalize_email", "UserService.create") in calls
    assert ("create", "AdminService.promote") in calls


def test_python_extractor_constants_and_exports():
    ex = extract_python(FIXTURE, "pkg/validators.py", (FIXTURE / "pkg/validators.py").read_text(encoding="utf-8"))
