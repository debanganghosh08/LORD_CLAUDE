def test_python_route_decorator_detected(tmp_path: Path):
    src = "from flask import Flask\napp = Flask(__name__)\n\n@app.route('/users')\ndef list_users():\n    return []\n"
    ex = extract_python(tmp_path, "api.py", src)
    route = next(s for s in ex.symbols if s.name == "list_users")
